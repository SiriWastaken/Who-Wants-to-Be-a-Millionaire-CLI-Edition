    // the "random" method to pick questions at the start of each game.
    public static List<Question> getGameQuestions() {
        List<Question> selected = new ArrayList<>();

        for (int diff = 1; diff <= 16; diff++) {
            List<Question> pool = new ArrayList<>();
            for (Question[] difficultyGroup : QUESTIONS) {
                for (Question q : difficultyGroup) {
                    if (q.getDifficulty() == diff) {
                        pool.add(q);
                    }
                }
            }
            if (!pool.isEmpty()) {
                Collections.shuffle(pool, random);
                selected.add(pool.get(0));
            }
        }

        return selected;
    }

